android {
    namespace = "com.lifeorganizer.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.lifeorganizer.app"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"
    }

    // Personal signing key is NOT part of this repository.
    // To sign builds with it, create keystore.properties in the project root:
    //   storeFile=keystore/organizer.keystore
    //   storePassword=...
    //   keyAlias=...
    //   keyPassword=...
    // Without that file, the standard debug key is used.
    val keystorePropsFile = rootProject.file("keystore.properties")
    val hasPersonalKey = keystorePropsFile.exists()
    if (hasPersonalKey) {
        val props = java.util.Properties().apply { keystorePropsFile.inputStream().use { load(it) } }
        signingConfigs {
            create("personal") {
                storeFile = rootProject.file(props.getProperty("storeFile"))
                storePassword = props.getProperty("storePassword")
                keyAlias = props.getProperty("keyAlias")
                keyPassword = props.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            if (hasPersonalKey) signingConfig = signingConfigs.getByName("personal")
        }
        debug {
            if (hasPersonalKey) signingConfig = signingConfigs.getByName("personal")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            all { it.maxHeapSize = "2g" }
        }
    }
}

