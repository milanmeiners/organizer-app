package com.lifeorganizer.app.data

import androidx.room.Entity
import androidx.room.PrimaryKey
import java.time.LocalDate
import java.time.LocalTime

enum class GoalStatus { ACTIVE, COMPLETED, ARCHIVED }

/** Status of a single occurrence of a recurring task. DELETED hides it, SKIPPED keeps it visible but crossed out. */
enum class OccurrenceStatus { OPEN, DONE, SKIPPED, DELETED }

/** Priority: 0 = none, 1 = low, 2 = medium, 3 = high. */
object Priority {
    const val NONE = 0
    const val LOW = 1
    const val MEDIUM = 2
    const val HIGH = 3
    fun label(p: Int): String = when (p) { LOW -> "Low"; MEDIUM -> "Medium"; HIGH -> "High"; else -> "None" }
}

@Entity(tableName = "goals")
data class Goal(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String,
    val description: String = "",
    val parentId: Long? = null,
    val deadline: LocalDate? = null,
    val priority: Int = Priority.NONE,
    val status: GoalStatus = GoalStatus.ACTIVE,
    /** Only used for goals without (active) subgoals. 0..100 */
    val manualProgress: Int? = null,
    val notes: String = "",
    val sortOrder: Int = 0,
    val createdAt: Long = System.currentTimeMillis(),
)

/**
 * A flexible task. If [rrule] is set, the task is a recurring series whose first occurrence is [startDate];
 * the state of each occurrence lives in [TaskOccurrence]. For one-time tasks [assignedDate] is the optional day
 * the user picked to work on it.
 */
@Entity(tableName = "tasks")
data class Task(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String,
    val description: String = "",
    val completed: Boolean = false,
    val completedAt: Long? = null,
    val trackProgress: Boolean = false,
    /** 0..100, only meaningful when [trackProgress] is true. Always set manually. */
    val progress: Int = 0,
    val priority: Int = Priority.NONE,
    val category: String = "",
    val startDate: LocalDate? = null,
    val deadline: LocalDate? = null,
    val assignedDate: LocalDate? = null,
    val rrule: String? = null,
    val goalId: Long? = null,
    val notes: String = "",
    /** Free-text personal working frequency, e.g. "3x per week". Never used for scheduling. */
    val workFrequency: String = "",
    val archived: Boolean = false,
    val sortOrder: Int = 0,
    val createdAt: Long = System.currentTimeMillis(),
)

val Task.isRecurring: Boolean get() = !rrule.isNullOrBlank()
val Task.isOpen: Boolean get() = !completed && !archived

/** Per-occurrence state of a recurring task. Rows exist only for occurrences that differ from the default. */
@Entity(tableName = "task_occurrences", primaryKeys = ["taskId", "date"])
data class TaskOccurrence(
    val taskId: Long,
    /** Original date generated by the recurrence rule. */
    val date: LocalDate,
    val status: OccurrenceStatus = OccurrenceStatus.OPEN,
    val titleOverride: String? = null,
    val notesOverride: String? = null,
    /** If set, this occurrence was moved to another day. */
    val movedTo: LocalDate? = null,
)

@Entity(tableName = "events")
data class Event(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String,
    val description: String = "",
    val date: LocalDate,
    val startTime: LocalTime,
    val endTime: LocalTime,
    val location: String = "",
    val rrule: String? = null,
    val createdAt: Long = System.currentTimeMillis(),
)

val Event.isRecurring: Boolean get() = !rrule.isNullOrBlank()

/** Change to a single occurrence of a recurring event (identified by its original date). */
@Entity(tableName = "event_exceptions", primaryKeys = ["eventId", "originalDate"])
data class EventException(
    val eventId: Long,
    val originalDate: LocalDate,
    val cancelled: Boolean = false,
    val date: LocalDate? = null,
    val startTime: LocalTime? = null,
    val endTime: LocalTime? = null,
    val title: String? = null,
    val description: String? = null,
    val location: String? = null,
)

/** Manual order of the to-do list of a day. [itemKey] is "t:<taskId>" or "o:<taskId>:<originalDate>". */
@Entity(tableName = "day_order", primaryKeys = ["date", "itemKey"])
data class DayOrder(
    val date: LocalDate,
    val itemKey: String,
    val position: Int,
)

/** Snapshot of everything stored; the UI derives all views from it. */
data class AppData(
    val tasks: List<Task> = emptyList(),
    val occurrences: List<TaskOccurrence> = emptyList(),
    val events: List<Event> = emptyList(),
    val exceptions: List<EventException> = emptyList(),
    val goals: List<Goal> = emptyList(),
    val dayOrders: List<DayOrder> = emptyList(),
)
